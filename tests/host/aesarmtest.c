static void fill(uint8_t *p, size_t n, uint32_t *seed) {
    while (n--) {
        *seed = *seed * 1664525u + 1013904223u;
        *p++ = (uint8_t)(*seed >> 24);
    }
}

int main(void) {
    static const uint8_t pt[16] = { 0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77,
                                    0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0xff };
    static const uint8_t ct[16] = { 0x8e, 0xa2, 0xb7, 0xca, 0x51, 0x67, 0x45, 0xbf,
                                    0xea, 0xfc, 0x49, 0x90, 0x4b, 0x49, 0x60, 0x89 };
    uint8_t key[32], key2[32], in[4096], a[4096], b[4096], back[4096], blk[16], dig[32];
    rwy_aes256_ctx_t aes;
    rwy_xts_ctx_t xa, xb;
    uint32_t seed = 1;
    int i;

    if (!rwy_has_armaes()) {
        printf("SKIP: no ARMv8 AES\n");
        return 77;
    }
    for (i = 0; i < 32; ++i)
        key[i] = (uint8_t)i;

    rwy_aes256_set_encrypt_key(&aes, key);
    rwy_aes256_encrypt_block(&aes, pt, blk);
    if (memcmp(blk, ct, 16)) { printf("FAIL: FIPS 197 encrypt\n"); return 1; }
    rwy_aes256_set_decrypt_key(&aes, key);
    rwy_aes256_decrypt_block(&aes, ct, blk);
    if (memcmp(blk, pt, 16)) { printf("FAIL: FIPS 197 decrypt\n"); return 1; }

    for (i = 0; i < 8; ++i) {
        uint64_t sector = (uint64_t)i * 0x100000001ull;

        fill(key, 32, &seed);
        fill(key2, 32, &seed);
        fill(in, sizeof in, &seed);

        rwy_crypto_set_portable(0);
        rwy_xts_init(&xa, key, key2);
        rwy_crypto_set_portable(1);
        rwy_xts_init(&xb, key, key2);

        rwy_crypto_set_portable(0);
        rwy_crypto_builtin_ops.xts_crypt(&xa, sector, in, a, sizeof in, 1);
        rwy_crypto_set_portable(1);
        rwy_crypto_builtin_ops.xts_crypt(&xb, sector, in, b, sizeof in, 1);
        if (memcmp(a, b, sizeof a)) { printf("FAIL: XTS encrypt differs, round %d\n", i); return 1; }

        rwy_sha256(a, sizeof a, dig);
        if (memcmp(dig, openssl_digest[i], 32)) { printf("FAIL: XTS differs from OpenSSL, round %d\n", i); return 1; }

        rwy_crypto_set_portable(0);
        rwy_crypto_builtin_ops.xts_crypt(&xa, sector, a, back, sizeof a, 0);
        if (memcmp(back, in, sizeof in)) { printf("FAIL: XTS round trip, round %d\n", i); return 1; }

        /* The random input as ciphertext: decrypt with both codes */
        rwy_crypto_builtin_ops.xts_crypt(&xa, sector, in, a, sizeof in, 0);
        rwy_crypto_set_portable(1);
        rwy_crypto_builtin_ops.xts_crypt(&xb, sector, in, b, sizeof in, 0);
        if (memcmp(a, b, sizeof a)) { printf("FAIL: XTS decrypt differs, round %d\n", i); return 1; }
    }
    rwy_crypto_set_portable(0);
    printf("PASS\n");
    return 0;
}
